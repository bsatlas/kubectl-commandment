package main

import (
	"testing"

	"github.com/abstractionsinc/commandment/cli"
	"github.com/abstractionsinc/commandment/clitest"
)

func TestExplainRequiresExactlyOneResource(t *testing.T) {
	t.Parallel()

	app, err := application(pluginCatalog{})
	if err != nil {
		t.Fatalf("Application() error = %v", err)
	}

	for _, args := range [][]string{{"explain"}, {"explain", "pods", "services"}} {
		request := cli.InspectionRequest{Args: args}
		clitest.Inspect(t.Context(), app, request).Require(t, clitest.InspectionRejected())
	}
}

func TestExplainRejectsUnsupportedOutput(t *testing.T) {
	t.Parallel()

	app, err := application(pluginCatalog{})
	if err != nil {
		t.Fatalf("Application() error = %v", err)
	}
	request := cli.InspectionRequest{Args: []string{"explain", "pods", "-o=json"}}

	clitest.Inspect(t.Context(), app, request).Require(t,
		clitest.InspectionRejected(),
		clitest.FailsWith(clitest.Diagnostic(cli.DiagnosticRuleViolation).Present()),
	)
}

